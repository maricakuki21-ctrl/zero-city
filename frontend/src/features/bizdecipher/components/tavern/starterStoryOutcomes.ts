/** Deterministic local rules: no network calls, hidden billing or fake dice. */
export function storyChoiceResponse(storyId: string, step: number, choice: number): string {
  const lines = storyId === 'last-letter' ? [
    ['你在新邮戳下找到旧日期，确认信并非凭空出现。', '邮差交出了退信簿：信早已到达，只是一直没有交给收信人。', '时间线有一处重叠：档案员离岗时，修钟师仍在大厅。'],
    ['留言属于收信人。她请求保存手稿，不是要求伪造一封新信。', '拨慢的十二分钟掩盖了档案柜被打开的时间，却没有改变信纸的年份。', '三人补全口供：旧信一直在柜中，只有保管档案的人能取出它。'],
    ['你的指认证据指向了能打开档案柜的人。', '钟声解释了时间差，却不足以证明寄信者是谁。', '日期冲突很诱人，但你尚未证明信来自未来。'],
  ] : [
    ['你登上旧塔，记住返回城市的轨道；代价是错过了第一次求救信号。', '水闸旁有新脚印，你带回一名失散乘客，却弄湿了备用线路。', '信号站传出求救坐标。你抄下位置，但城里的灯已经看不见了。'],
    ['你修好供电旁路，列车和道岔现在可以分开供电。', '敲击声不是故障，是有人在重复人数和位置；你掌握了救援线索。', '同行者校准时钟，发现安全切换道岔的窗口只有十二秒。'],
    ['你将路线带回城里，救援的责任不再只落在这一车人身上。', '你把唯一的灯留在雾里，列车上的每个人都要为返程多走一段。', '你安排两组人分别守住道岔和车门，试着让救援与返程同时发生。'],
  ]
  return lines[step]?.[choice] ?? ''
}

export function storyEnding(storyId: string, choices: readonly string[]): { title: string; text: string } {
  if (storyId === 'last-letter') {
    const correct = choices[2] === '档案员重新投递了旧信'
    return correct
      ? { title: '结局 · 迟到的告别', text: '你没有被明天的日期迷惑。档案员承认，他把柜中的旧信重新投递，只为让三个人重新坐在同一张桌前。修钟师拨慢时钟替他争取时间，邮差则一直替收信人保存退信。没有未来来信，只有一封迟迟不敢送出的告别。你把旧邮戳与档案柜编号一起留进了记录。' }
      : { title: '结局 · 尚未寄达的真相', text: '你的判断没能解释旧信封里的档案柜编号。档案员最终把钥匙放上桌：是他重新投递了旧信；钟声只是掩护，未来的日期只是邀请。没有人责怪你的猜测，但你决定下次先核对证据，再相信最动人的说法。' }
  }
  if (choices[2] === '先返回城市召集救援') return {
    title: '结局 · 带着坐标归来', text: '列车重新获得了方向。你们先回到城里，把雾中的坐标交给救援队。' + (choices[0] === '前往旧塔寻找高处视野' ? '旧塔上记下的轨道让返程少走了一段弯路。' : '返程比预计更久，车厢里没有人庆祝，直到第二班车带着灯出发。') + '你救下的不是所有人，而是下一次救援的机会。',
  }
  if (choices[2] === '把灯留给求助者') return {
    title: '结局 · 留在雾里的灯', text: '列车重新获得了方向，但你们没有立刻出发。灯留给了求助者，返程改为步行护送。' + (choices[0] === '沿水闸寻找人类活动' ? '先前遇见的乘客认出了水闸旁的小路，把队伍带回城门。' : '你们轮流扶着车厢边缘前进，把恐惧说成故事，直到看见城里的第一盏灯。'),
  }
  const prepared = choices[1] === '检修电源和线路' || choices[1] === '请同行者检查时钟'
  return prepared
    ? { title: '结局 · 一起回城', text: '列车重新获得了方向。先前完成的设备准备派上用场：两组人在切换窗口内复位道岔，让求助者登车，也保住了返程轨道。你们带回的不只是路线，还有一种经验——互相照应，必须落实到有人守门、有人修路。' }
    : { title: '结局 · 第二班救援', text: '列车重新获得了方向，但道岔没有在预定时间复位。你们掌握了求救线索，却缺少设备准备，只能先把位置传回城里，原地守住受困者，等待第二班救援。勇气让你们留下，准备才能让所有人回家。' }
}
